def build_docs(news_rows: list[News]) -> list[dict]:
    splitter = RecursiveCharacterTextSplitter(
        chunk_size=220,
        chunk_overlap=20,
        separators=["\n\n", "\n", "。", "；", "，", " ", ""],
    )
    docs = []
    for news in news_rows:
        if not news.content:
            continue
        for i, chunk in enumerate(splitter.split_text(news.content)):
            docs.append({
                "news_id": news.id,
                "title": news.title,
                "category_id": news.category_id,
                "text": chunk,
                "chunk_index": i,
            })
    return docs


async def seed_news() -> list[News]:
    titles = [item["title"] for item in NEWS_ITEMS]
    async with AsyncSessionLocal() as session:
        existing = await session.execute(
            select(News).where(News.title.in_(titles))
        )
        existing_titles = {row.title for row in existing.scalars().all()}

        created = []
        for item in NEWS_ITEMS:
            if item["title"] in existing_titles:
                continue
            news = News(
                title=item["title"],
                description=item["description"],
                content=item["content"],
                author=item["author"],
                category_id=item["category_id"],
                views=0,
                publish_time=datetime(2025, 9, 20, 10, 0, 0),
            )
            session.add(news)
            created.append(news)

        await session.commit()
        print(f"新增新闻: {len(created)}")

        rows = await session.execute(select(News).where(News.title.in_(titles)))
        return list(rows.scalars().all())


async def index_large_news(news_rows: list[News]) -> None:
    client = MilvusClient(MILVUS_URI)
    if not client.has_collection(COLLECTION):
        client.create_collection(
            collection_name=COLLECTION,
            dimension=EMBED_DIM,
            metric_type="COSINE",
            enable_dynamic_field=True,
        )

    indexed_news_ids = {
        int(row["news_id"])
        for row in client.query(
            COLLECTION,
            filter="news_id >= 0",
            output_fields=["news_id"],
        )
    }
    pending_rows = [row for row in news_rows if row.id not in indexed_news_ids]
    if not pending_rows:
        print("没有需要新写入 Milvus 的新闻")
        return

    docs = build_docs(pending_rows)
    vectors = embeddings.embed_documents([d["text"] for d in docs])

    existing = client.query(
        COLLECTION,
        filter="id >= 0",
        output_fields=["id"],
    )
    next_id = max((int(row["id"]) for row in existing), default=0) + 1

    rows = [
        {"id": next_id + i, "vector": vec, **doc}
        for i, (doc, vec) in enumerate(zip(docs, vectors))
    ]
    client.insert(collection_name=COLLECTION, data=rows)
    stats = client.get_collection_stats(COLLECTION)
    print(f"新增 Milvus chunk: {len(rows)}")
    print(f"当前 collection row_count: {stats.get('row_count')}")


